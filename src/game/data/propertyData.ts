export function getPropertyById(id: string): PropertyDef | undefined {
  return PROPERTIES_CATALOG.find((p) => p.id === id);
}

export function getPropertyByBuildingId(buildingId: string): PropertyDef | undefined {
  return PROPERTIES_CATALOG.find((p) => p.buildingId === buildingId);
}

export function buildDefaultDeed(
  prop: PropertyDef,
  ownerUid: string,
  ownerUsername: string,
  allowVisitors = true,
): PropertyDeed {
  return {
    deedId: `${ownerUid}__${prop.id}`,
    ownerUid,
    ownerUsername,
    propertyId: prop.id,
    title: prop.name,
    tier: prop.tier,
    allowVisitors,
    invitedUids: [],
    floorStyle: prop.defaultFloorStyle,
    wallStyle: prop.defaultWallStyle,
    furniture: prop.defaultFurniture.map((f) => ({...f})),
    updatedAtMs: Date.now(),
  };
}
